'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname, '../..'),src=path.join(root,'src');
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
function buildRelease(){
    const paths=JSON.parse(fs.readFileSync(path.join(__dirname,'offline-assets.json'),'utf8'));
    const template=fs.readFileSync(path.join(__dirname,'service-worker.template.js'),'utf8');
    const version=require('../../src/js/workspace-app.js').WorkspaceApp.version;
    if(!/^\d+\.\d+\.\d+$/.test(version))throw new Error('Application version missing');
    const rawLegal=require('./build-legal.cjs').legalPages();
    const whoSources=require('./build-who-source-package.cjs').sourcePackage();
    const appSources=require('./build-source-archive.cjs').sourceArchive();
    const generated={'data/who-data-sources.zip':whoSources.zip,'data/who-data-sources.json':whoSources.metadata,'data/zscore-sources.zip':appSources.zip,'data/zscore-sources.json':appSources.metadata};
    const assets={};
    for(const asset of paths){
        if(asset!=='./'&&(!/^[\w./-]+$/.test(asset)||asset.includes('..')||asset.startsWith('/')))throw new Error('Unsafe asset path');
        if(generated[asset]||rawLegal[asset]){assets[asset]=sha(generated[asset]||Buffer.from(rawLegal[asset]));continue;}
        const filename=path.join(src,asset==='./'?'index.html':asset);
        if(!fs.statSync(filename).isFile())throw new Error('Missing asset: '+asset);
        assets[asset]=sha(fs.readFileSync(filename));
    }
    const index=renderIntegrity(fs.readFileSync(path.join(src,'index.html'),'utf8'),assets);
    const legal=Object.fromEntries(Object.entries(rawLegal).map(([file,html])=>[file,renderIntegrity(html,assets)]));
    for(const [file,html]of Object.entries(legal))assets[file]=sha(html);
    assets['index.html']=assets['./']=sha(index);
    const release={format:1,version,assets,workerTemplateSHA256:sha(template)};
    release.id=sha(JSON.stringify(release));
    return {release,index,legal,generated,worker:'/* Generated by node scripts/build-release.cjs. Edit the template and rebuild. */\nconst RELEASE = '+JSON.stringify(release,null,2)+';\n'+template,
        manifest:JSON.stringify(release,null,2)+'\n'};
}
function renderIntegrity(html,assets){
    html=html.replace(/<(script|link)\b[^>]*>/g,tag=>{
        if(tag.startsWith('<link')&&!/rel="stylesheet"/.test(tag))return tag;
        const file=tag.match(/(?:src|href)="([^"]+)"/)?.[1];
        if(!file||!assets[file])throw new Error('Resource outside the release manifest: '+file);
        const clean=tag.replace(/\s+integrity="[^"]*"/g,'').replace(/>$/,m=>/\bcrossorigin=/.test(tag)?m:' crossorigin="anonymous"'+m);
        return clean.slice(0,-1)+' integrity="sha256-'+Buffer.from(assets[file],'hex').toString('base64')+'">';
    });
    const pins=Object.fromEntries(['data/interface-translations.json','data/who-manifest.json','data/who-official.json','data/who-2007.json','data/who-2007-manifest.json','data/LICENSE-anthroplus.txt',...require('../../src/js/services/pdf-manager.js').PDFManager.fontPaths].map(p=>[p,assets[p]]));
    if(Object.values(pins).some(hash=>!hash))throw new Error('Missing initial data asset');
    const meta='<meta name="zscore-data-integrity" content="'+JSON.stringify(pins).replace(/"/g,'&quot;')+'">';
    if(/<meta name="zscore-data-integrity"[^>]*>/.test(html))return html.replace(/<meta name="zscore-data-integrity"[^>]*>/,meta);
    return html.replace('</head>','    '+meta+'\n</head>');
}
function checkRelease(){
    const expected=buildRelease();
    for(const [file,bytes]of [['index.html',expected.index],...Object.entries(expected.legal),...Object.entries(expected.generated),['sw.js',expected.worker],['release-manifest.json',expected.manifest]]){
        if(!fs.existsSync(path.join(src,file))||!fs.readFileSync(path.join(src,file)).equals(Buffer.from(bytes)))throw new Error('Stale release: run npm run build:release before serving or publishing');
    }
    return expected.release;
}
if(require.main===module){
    const expected=buildRelease();
    if(process.argv.includes('--check'))checkRelease();
    else{for(const [file,b]of Object.entries(expected.generated))fs.writeFileSync(path.join(src,file),b);for(const [file,html]of Object.entries(expected.legal))fs.writeFileSync(path.join(src,file),html);fs.writeFileSync(path.join(src,'index.html'),expected.index);fs.writeFileSync(path.join(src,'sw.js'),expected.worker);fs.writeFileSync(path.join(src,'release-manifest.json'),expected.manifest);}
    console.log(JSON.stringify({release:expected.release.id,version:expected.release.version,files:Object.keys(expected.release.assets).length},null,2));
}
module.exports={buildRelease,checkRelease,renderIntegrity};
